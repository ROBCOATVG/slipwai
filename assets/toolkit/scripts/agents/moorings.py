#!/usr/bin/env python3
"""Where one slice is worked: a worktree of its own, so two slices of one fairway never share a checkout.

The captain ran its one `/sail` with the project's own checkout as the session's directory, and the
session made itself a worktree because *Running ready slices concurrently* says each slice has one. That
held while there was one session: nothing else was in the checkout to collide with. Two sessions in one
checkout are two agents running `git checkout` under each other, and the second one's branch is whatever
the first left — the failure is not a conflict anybody sees but commits landing on the wrong slice.

**So the captain makes the berth, and the session starts in it.** `../<project>-<id>` on `slice/<id>` —
the name `commands/sail.md` and `dispatch.py` already give a slice's worktree, so one a person or an
earlier session made is found and used rather than made twice. A slice whose branch is already checked
out somewhere — a takeover lands it in the project's checkout — is worked where it is.

**The deck log is the one thing a berth must not have its own copy of.** It is ignored by git, so a
worktree starts without one, and a session in a berth writing `.slipwai/run/logs/...` would write lines the
captain is not reading — every one of them a gate the captain then says was never passed. The berth's
`.slipwai/run/logs` is a link to the project's. Under `.slipwai/run/` git ignores it with the rest; in a
project not migrated yet the link is listed in the repository's own `info/exclude`, which every worktree
shares, because that `.gitignore` names the directory with a trailing slash and a link is not a directory
to git.

**A berth is furnished with what git does not carry, before every run of its slice.** A worktree is the committed tree and nothing
else, and a session needs three things that are not committed: the projected commands and delegates under
`.claude/` (generated by `scripts/agents/project.py`, and ignored), without which `/drive` is not a
command at all; the project's `.env`, ignored for the reason every secret is; and — for a branch cut
before it was committed — the MCP file, which the harness now passes by the project's absolute path
instead. The first run of hr-test-2's slices abreast exited 1 three times in six seconds on the last of
these, and would have met the first next.

**A berth is left when its slice merges.** Without `--force`: a worktree with changes in it is somebody's,
and the line that says it was kept is cheaper than the work it would have cost.

Standalone and dependency-free: this runs inside a generated project, which has no slipwai to import.
"""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import logs  # noqa: E402 — carried beside this script; it owns where the run's state lives


def excluded(berth: Path) -> str:
    """What a worktree's deck-log link is excluded as, in the repository's shared `info/exclude`."""
    return "/" + logs.logs_dir(berth).relative_to(berth).as_posix()


def is_link(path: Path) -> bool:
    """Whether `path` is a link to a folder elsewhere: a symlink, or on Windows the junction made in its place."""
    if path.is_symlink():
        return True
    is_junction = getattr(os.path, "isjunction", None)  # Python 3.12 and later
    if is_junction is not None:
        return bool(is_junction(path))
    try:
        return bool(getattr(os.lstat(path), "st_file_attributes", 0) & 0x400)  # a reparse point
    except OSError:
        return False


def link_folder(target: Path, link: Path) -> None:
    """`link` pointing at the folder `target`: a symlink, except on Windows, where a symlink needs Developer
    Mode or an administrator and a junction, which needs neither, stands in."""
    if os.name == "nt":  # pragma: no cover - the other platform's branch
        import _winapi  # noqa: PLC0415 — Windows only

        _winapi.CreateJunction(str(target), str(link))
        return
    os.symlink(target, link, target_is_directory=True)


def git(root: Path, *argv: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(["git", *argv], cwd=root, capture_output=True, text=True, check=False,
                          encoding="utf-8", errors="replace")


def checked_out(root: Path, branch: str) -> Path | None:
    """The worktree that has this branch checked out, or None where none has."""
    listed = git(root, "worktree", "list", "--porcelain")
    where: Path | None = None
    for line in listed.stdout.splitlines():
        if line.startswith("worktree "):
            where = Path(line[len("worktree "):])
        elif line == f"branch refs/heads/{branch}" and where is not None:
            return where
    return None


def linked(root: Path, berth: Path) -> str:
    """Point the berth's deck logs at the project's, and say why where that could not be done."""
    here = logs.logs_dir(berth)
    shared = logs.logs_dir(root)
    shared.mkdir(parents=True, exist_ok=True)
    if is_link(here) or berth.resolve() == root.resolve():
        return ""
    said = ""
    if here.is_dir():
        try:
            here.rmdir()  # empty, and so nothing anybody wrote
        except OSError:
            # Lines a session wrote before the berth was linked: kept, beside the link, rather than left
            # where every later line would land too and the gate would read none of them.
            aside = here.with_name(f"logs.unread-{time.strftime('%Y%m%dT%H%M%S')}")
            try:
                here.rename(aside)
            except OSError as fault:
                return f"{here} has lines in it and could not be moved aside ({fault}), so the gate will not see them"
            said = f"{here} had lines a session wrote before it was linked; they are kept at {aside}"
    here.parent.mkdir(parents=True, exist_ok=True)
    try:
        link_folder(shared.resolve(), here)
    except OSError as fault:
        return f"{here} could not be linked to the project's deck logs ({fault})"
    common = git(root, "rev-parse", "--git-common-dir").stdout.strip()
    if common:
        exclude = (root / common).resolve() / "info/exclude"
        held = exclude.read_text(encoding="utf-8") if exclude.is_file() else ""
        line = excluded(berth)
        if line not in held.splitlines():
            exclude.parent.mkdir(parents=True, exist_ok=True)
            joined = held + ("" if held.endswith("\n") or not held else "\n") + line + "\n"
            exclude.write_text(joined, encoding="utf-8")
    return said


def furnished(root: Path, berth: Path) -> str:
    """Give the berth what a session needs and git does not carry; say what could not be given, or nothing."""
    if berth.resolve() == root.resolve():
        return ""
    faults: list[str] = []
    env, here = root / ".env", berth / ".env"
    if env.is_file() and not here.exists() and not here.is_symlink():
        try:
            if os.name == "nt":  # a file symlink there needs Developer Mode or an administrator
                shutil.copy2(env, here)
            else:
                os.symlink(env.resolve(), here)
        except OSError as fault:
            faults.append(f".env could not be linked ({fault})")
    projector = berth / "scripts/agents/project.py"
    if projector.is_file():
        done = subprocess.run([sys.executable, str(projector)], cwd=berth, capture_output=True, text=True,
                              check=False)
        if done.returncode != 0:
            said = (done.stderr or done.stdout).strip().splitlines()
            faults.append(f"the agent projection failed in {berth}: {said[-1] if said else 'no output'}")
    faults += skills_carried(root, berth)
    return "; ".join(faults)


def skills_carried(root: Path, berth: Path) -> list[str]:
    """Copy into the berth every skill the project's checkout has and the berth does not.

    The projection writes slipwai's own skills, and Spec Kit's — `speckit-*`, installed by `specify init`
    and managed by the harness — are written by nothing a worktree runs: `.claude/skills/` is ignored, so a
    berth starts without them and `check-speckit` refuses the slice. hr-test-2's L03, L06 and L04 each
    parked on it for a person to copy them in by hand. Only what is missing is copied, so a skill the
    projection just wrote is never overwritten with the checkout's older copy.
    """
    source, target = root / ".claude/skills", berth / ".claude/skills"
    if not source.is_dir() or source.resolve() == target.resolve():
        return []
    faults = []
    for skill in sorted(source.iterdir()):
        if not skill.is_dir() or (target / skill.name).exists():
            continue
        try:
            shutil.copytree(skill, target / skill.name, symlinks=True)
        except OSError as fault:
            faults.append(f"the skill {skill.name} could not be carried into {berth} ({fault})")
    return faults


def berth(root: Path, slice_id: str, branch: str, base: str) -> tuple[Path | None, str]:
    """The slice's own worktree, made where it is not there yet. (where, why not).

    None where there is no commit to make one from — a harbour with no history — or git refused; the
    caller decides whether the checkout itself will do, which it will only while nothing else is in it.
    """
    if git(root, "rev-parse", "--verify", "--quiet", "HEAD").returncode != 0:
        return None, "this checkout has no commit yet, so there is nothing to make a worktree from"
    found = checked_out(root, branch)
    if found is None:
        found = root.parent / f"{root.name}-{slice_id}"
        if found.exists():
            # Both steps, because nothing re-checks the berth and a slice with an open park is skipped:
            # hr-test-2's L04 was told go without the berth being moved, and parked again.
            return None, (f"{found} is already there and is not a worktree on {branch}. Move it, or "
                          f"check {branch} out in it, then answer this park (say go) and the slice is "
                          f"carried on")
        made = add_worktree(root, found, branch, base)
        if made.returncode != 0:
            said = (made.stderr or made.stdout).strip().splitlines()
            return None, f"a worktree for {branch} could not be made: {said[-1] if said else 'git failed'}"
    notes = [note for note in (linked(root, found), furnished(root, found)) if note]
    return found, "; ".join(notes)


def add_worktree(root: Path, found: Path, branch: str, base: str) -> subprocess.CompletedProcess[str]:
    """`git worktree add`, tried again where a sibling's was half-made at the same instant.

    Captains abreast make their berths together, and git reads every other worktree's admin folder while it
    makes one: on Windows a sibling's `.git/worktrees/<name>/commondir` can be there and still empty, and
    git refuses with `failed to read ... commondir`. The berth was then parked as unmakeable for a race that
    was over a moment later. Whether the branch exists is asked each time, because `-b` makes it before the
    worktree and a failed attempt can leave it behind.
    """
    for attempt in range(4):
        exists = git(root, "rev-parse", "--verify", "--quiet", f"refs/heads/{branch}").returncode == 0
        made = (git(root, "worktree", "add", "--quiet", str(found), branch) if exists
                else git(root, "worktree", "add", "--quiet", "-b", branch, str(found), base or "HEAD"))
        if made.returncode == 0 or "worktrees/" not in (made.stderr or "") or found.exists():
            return made
        time.sleep(0.25 * (attempt + 1))
    return made


def leave(root: Path, berth: Path) -> str:
    """Remove a merged slice's worktree, or say why it was kept. Never the project's own checkout."""
    if berth.resolve() == root.resolve():
        return ""
    here = logs.logs_dir(berth)
    if os.name == "nt" and is_link(here):  # pragma: no cover - the other platform's branch
        # Git reads the junction as a folder of the worktree's own and keeps the berth; `rmdir` takes the
        # junction alone, and the deck logs it joins are not touched.
        os.rmdir(here)
    gone = git(root, "worktree", "remove", str(berth))
    if gone.returncode != 0:
        said = (gone.stderr or gone.stdout).strip().splitlines()
        return f"{berth} was kept: {said[-1] if said else 'git would not remove it'}"
    return ""
