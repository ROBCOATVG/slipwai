#!/usr/bin/env python3
"""Where one slice is worked: a worktree of its own, so two slices of one fairway never share a checkout.

The captain ran its one `/sail` with the project's own checkout as the session's directory, and the
session made itself a worktree because *Running ready slices concurrently* says each slice has one. That
held while there was one session: nothing else was in the checkout to collide with. Two sessions in one
checkout are two agents running `git checkout` under each other, and the second one's branch is whatever
the first left — the failure is not a conflict anybody sees but commits landing on the wrong slice.

**So the captain makes the berth, and the session starts in it.** `../<project>-<id>` on `slice/<id>` —
the name `commands/sail.md` and `dispatch.py` already give a slice's worktree, so one a person or an
earlier session made is found and used rather than made twice. A slice whose branch is already checked
out somewhere — a takeover lands it in the project's checkout — is worked where it is.

**The deck log is the one thing a berth must not have its own copy of.** It is ignored by git, so a
worktree starts without one, and a session in a berth writing `.slipwai/run/logs/...` would write lines the
captain is not reading — every one of them a gate the captain then says was never passed. The berth's
`.slipwai/run/logs` is a link to the project's. Under `.slipwai/run/` git ignores it with the rest; in a
project not migrated yet the link is listed in the repository's own `info/exclude`, which every worktree
shares, because that `.gitignore` names the directory with a trailing slash and a link is not a directory
to git.

**A berth is furnished with what git does not carry, before every run of its slice.** A worktree is the committed tree and nothing
else, and a session needs three things that are not committed: the projected commands and delegates under
`.claude/` (generated by `scripts/agents/project.py`, and ignored), without which `/drive` is not a
command at all; the project's `.env`, ignored for the reason every secret is; and — for a branch cut
before it was committed — the MCP file, which the harness now passes by the project's absolute path
instead. The first run of hr-test-2's slices abreast exited 1 three times in six seconds on the last of
these, and would have met the first next.

**A berth is left when its slice merges.** A worktree whose tracked files are edited and not committed is
somebody's, and the line that says it was kept is cheaper than the work it would have cost. Anything else in it
goes, and so does whatever is still running there: the slice's Try it processes and any process working in the
folder are stopped first, because one writing while git deletes left twelve of manda's merged berths beside
the project with git's record of them already gone.

Standalone and dependency-free: this runs inside a generated project, which has no slipwai to import.
"""
from __future__ import annotations

import json
import os
import shutil
import signal
import stat
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
import logs  # noqa: E402 — carried beside this script; it owns where the run's state lives
import talk  # noqa: E402 — the one reader for a file in the run folder


def is_link(path: Path) -> bool:
    """Whether `path` is a link to a folder elsewhere: a symlink, or on Windows the junction made in its place."""
    if path.is_symlink():
        return True
    is_junction = getattr(os.path, "isjunction", None)  # Python 3.12 and later
    if is_junction is not None:
        return bool(is_junction(path))
    try:
        return bool(getattr(os.lstat(path), "st_file_attributes", 0) & 0x400)  # a reparse point
    except OSError:
        return False


def link_folder(target: Path, link: Path) -> None:
    """`link` pointing at the folder `target`: a symlink, except on Windows, where a symlink needs Developer
    Mode or an administrator and a junction, which needs neither, stands in."""
    if os.name == "nt":  # pragma: no cover - the other platform's branch
        import _winapi  # noqa: PLC0415 — Windows only

        _winapi.CreateJunction(str(target), str(link))
        return
    os.symlink(target, link, target_is_directory=True)


def git(root: Path, *argv: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(["git", *argv], cwd=root, capture_output=True, text=True, check=False,
                          encoding="utf-8", errors="replace")


def checked_out(root: Path, branch: str) -> Path | None:
    """The worktree that has this branch checked out, or None where none has."""
    listed = git(root, "worktree", "list", "--porcelain")
    where: Path | None = None
    for line in listed.stdout.splitlines():
        if line.startswith("worktree "):
            where = Path(line[len("worktree "):])
        elif line == f"branch refs/heads/{branch}" and where is not None:
            return where
    return None


def mid_rebase(root: Path, branch: str) -> Path | None:
    """The worktree a rebase of this branch was left open in, put back on the branch; None where none was.

    A session rebasing its slice when the fleet is stopped leaves its worktree on a detached HEAD with the
    rebase open. Nothing then has the branch checked out, the folder is in the way of a new worktree, and the
    slice parked for a person to "move it, or check the branch out in it" (manda's S95). The rebase is aborted,
    which is the branch as the session last committed it: the harbourmaster rebases at the merge anyway.
    """
    listed = git(root, "worktree", "list", "--porcelain")
    for line in listed.stdout.splitlines():
        if not line.startswith("worktree "):
            continue
        where = Path(line[len("worktree "):])
        for kind in ("rebase-merge", "rebase-apply"):
            named = git(where, "rev-parse", "--git-path", f"{kind}/head-name").stdout.strip()
            try:
                held = (where / named).read_text(encoding="utf-8").strip() if named else ""
            except OSError:
                continue
            if held == f"refs/heads/{branch}" and git(where, "rebase", "--abort").returncode == 0:
                return where
    return None


def points_at(link: Path, target: Path) -> bool:
    """Whether `link` is a link that reaches `target`. A link to a folder since moved reaches nothing."""
    try:
        return is_link(link) and link.resolve() == target.resolve() and target.is_dir()
    except OSError:
        return False


def places(berth: Path) -> list[Path]:
    """Where a berth's sessions may look for the deck logs: where its own tree says, and — for a berth cut
    before the project moved its run state — where the tree will say once it is rebased onto that."""
    here = logs.logs_dir(berth)
    after = berth / logs.RUN / "logs"
    return [here] if here == after else [here, after]


def linked(root: Path, berth: Path) -> str:
    """Point the berth's deck logs at the project's, and say why where that could not be done.

    **Held to where the link goes, not to there being one.** A migration moves the project's logs to
    `.slipwai/run/logs`, and a berth made before it keeps a link to the folder that is no longer there:
    game-club-manager's AC4 wrote its `seeded` line by hand because the seed's own write fell through a
    dangling link, and TB1, rebased onto the migrated trunk mid-run, found its new place unlinked and was
    refused both ways of mending it. So a link that reaches anything but the project's logs is made again,
    and a berth still on the old layout is given the new place as well, for the rebase that is coming.
    """
    if berth.resolve() == root.resolve():
        return ""
    shared = logs.logs_dir(root)
    shared.mkdir(parents=True, exist_ok=True)
    notes = [note for note in (linked_at(root, berth, place, shared) for place in places(berth)) if note]
    return "; ".join(notes)


def linked_at(root: Path, berth: Path, here: Path, shared: Path) -> str:
    """One place in the berth pointed at the project's logs. What `linked` does, for each of `places`."""
    if points_at(here, shared):
        return ""
    said = ""
    if is_link(here):
        try:
            here.rmdir() if os.name == "nt" else here.unlink()
        except OSError as fault:
            return f"{here} is a link to somewhere that is not the project's deck logs and could not be remade ({fault})"
    if here.is_dir():
        try:
            here.rmdir()  # empty, and so nothing anybody wrote
        except OSError:
            # Lines a session wrote before the berth was linked: kept, beside the link, rather than left
            # where every later line would land too and the gate would read none of them.
            aside = here.with_name(f"logs.unread-{time.strftime('%Y%m%dT%H%M%S')}")
            try:
                here.rename(aside)
            except OSError as fault:
                return f"{here} has lines in it and could not be moved aside ({fault}), so the gate will not see them"
            said = f"{here} had lines a session wrote before it was linked; they are kept at {aside}"
    here.parent.mkdir(parents=True, exist_ok=True)
    try:
        link_folder(shared.resolve(), here)
    except OSError as fault:
        return f"{here} could not be linked to the project's deck logs ({fault})"
    common = git(root, "rev-parse", "--git-common-dir").stdout.strip()
    if common:
        exclude = (root / common).resolve() / "info/exclude"
        held = exclude.read_text(encoding="utf-8") if exclude.is_file() else ""
        line = "/" + here.relative_to(berth).as_posix()
        if line not in held.splitlines():
            exclude.parent.mkdir(parents=True, exist_ok=True)
            joined = held + ("" if held.endswith("\n") or not held else "\n") + line + "\n"
            exclude.write_text(joined, encoding="utf-8")
    return said


def furnished(root: Path, berth: Path) -> str:
    """Give the berth what a session needs and git does not carry; say what could not be given, or nothing."""
    if berth.resolve() == root.resolve():
        return ""
    faults: list[str] = []
    env, here = root / ".env", berth / ".env"
    if env.is_file() and not here.exists() and not here.is_symlink():
        try:
            if os.name == "nt":  # a file symlink there needs Developer Mode or an administrator
                shutil.copy2(env, here)
            else:
                os.symlink(env.resolve(), here)
        except OSError as fault:
            faults.append(f".env could not be linked ({fault})")
    projector = berth / "scripts/agents/project.py"
    if projector.is_file():
        done = subprocess.run([sys.executable, str(projector)], cwd=berth, capture_output=True, text=True,
                              check=False)
        if done.returncode != 0:
            said = (done.stderr or done.stdout).strip().splitlines()
            faults.append(f"the agent projection failed in {berth}: {said[-1] if said else 'no output'}")
    faults += skills_carried(root, berth)
    return "; ".join(faults)


def generator(where: Path, ref: str) -> str:
    """What `project.json` at this commit says the project was generated and last migrated with, as one string."""
    shown = git(where, "show", f"{ref}:project.json")
    if shown.returncode != 0:
        return ""
    try:
        return json.dumps(json.loads(shown.stdout).get("generator", {}), sort_keys=True)
    except (ValueError, AttributeError):
        return ""


#: How the commit that takes a migration into a berth begins, which is how a later take knows it.
TAKEN = "Take the project's migration"


def migration_files(berth: Path, trunk: str) -> list[str]:
    """Every file a migration changed on trunk since this berth left it: what `slipwai migrate` brought.

    The commits on trunk's own line that moved `project.json`'s `generator`, each compared with the trunk
    before it. A migration's merge commit has the project as its first parent, so that comparison is the
    migration and nothing a slice wrote.
    """
    base = git(berth, "merge-base", "HEAD", trunk).stdout.strip()
    if not base:
        return []
    found: set[str] = set()
    moved = git(berth, "log", "--first-parent", "--format=%H", f"{base}..{trunk}", "--", "project.json")
    for commit in moved.stdout.split():
        if generator(berth, commit) != generator(berth, f"{commit}^1"):
            found |= set(git(berth, "diff", "--name-only", f"{commit}^1", commit).stdout.splitlines())
    return sorted(found)


def caught_up(root: Path, berth: Path, trunk: str) -> str:
    """Take a migration into a berth cut before it: its files, as trunk has them. Say what happened, or nothing.

    A berth meets trunk when its slice merges and not before, so a slice in flight when `slipwai migrate`
    landed kept the scripts and the ladder it was cut with for the rest of its life. lean-coffee-club was
    migrated on 2026-11-18 to bound its demo walks and stop reading each slice; the one slice cut after it
    had both, and the four already in flight had neither until a person brought trunk into each by hand.

    **Only the migration is taken, never a sibling's work**, which the slice meets at its merge as it always
    has. The first cut of this merged the whole of trunk, and the next day three of five berths refused it:
    a sibling's merged code conflicted with the slice's own, the merge was abandoned, and those slices ran
    on the old pages. So the files the migration changed are checked out as trunk has them, and committed.
    When the slice lands, the harbourmaster's rebase finds trunk already says the same and drops the commit.
    A file of the migration that the slice has changed itself is left as the slice has it, and named.
    """
    if not trunk or berth.resolve() == root.resolve():
        return ""
    wanted, held = generator(berth, trunk), generator(berth, "HEAD")
    if not wanted or wanted == held:
        return ""
    if git(berth, "merge-base", "--is-ancestor", trunk, "HEAD").returncode == 0:
        return ""
    files = migration_files(berth, trunk)
    base = git(berth, "merge-base", "HEAD", trunk).stdout.strip()
    # What the slice changed itself, and not what an earlier migration's take put there: read from every
    # commit but those. manda was migrated three times in a day, and a slice in flight took the first and
    # none after — the files it had been given once were its own from then on.
    own = set(git(berth, "log", "--format=", "--name-only", "--invert-grep", f"--grep=^{TAKEN}",
                  f"{base}..HEAD", "--", *files).stdout.split("\n")) - {""} if files else set()
    own |= {line[3:] for line in git(berth, "status", "--porcelain", "--", *files).stdout.splitlines()} if files else set()
    taken = [path for path in files if path not in own]
    if not taken:
        return (f"{berth.name} was cut before the project's last migration and nothing of it could be taken "
                f"from {trunk}; it runs on the version it was cut with until it merges")
    for path in taken:
        there = git(berth, "cat-file", "-e", f"{trunk}:{path}").returncode == 0
        done = git(berth, "checkout", trunk, "--", path) if there else git(berth, "rm", "-q", "--ignore-unmatch", "--", path)
        if done.returncode != 0:
            said = (done.stderr or done.stdout).strip().splitlines()
            git(berth, "reset", "-q", "--", *taken)
            git(berth, "checkout", "--", *[one for one in taken if (berth / one).exists()])
            return (f"{berth.name} was cut before the project's last migration and could not take it from "
                    f"{trunk} ({said[-1] if said else 'git refused'}); it runs on the version it was cut "
                    f"with until it merges")
    committed = git(berth, "commit", "-q", "-m", f"{TAKEN} from {trunk}: its files only",
                    "--", *taken)
    if committed.returncode != 0:
        said = (committed.stderr or committed.stdout).strip().splitlines()
        return (f"{berth.name} took the project's last migration from {trunk} and could not commit it "
                f"({said[-1] if said else 'git refused'})")
    kept = f"; {', '.join(sorted(own))} it changed itself and kept" if own else ""
    return (f"{berth.name} was cut before the project's last migration and has taken its {len(taken)} "
            f"file(s) from {trunk}{kept}")


def skills_carried(root: Path, berth: Path) -> list[str]:
    """Copy into the berth every skill the project's checkout has and the berth does not.

    The projection writes slipwai's own skills, and Spec Kit's — `speckit-*`, installed by `specify init`
    and managed by the harness — are written by nothing a worktree runs: `.claude/skills/` is ignored, so a
    berth starts without them and `check-speckit` refuses the slice. hr-test-2's L03, L06 and L04 each
    parked on it for a person to copy them in by hand. Only what is missing is copied, so a skill the
    projection just wrote is never overwritten with the checkout's older copy.
    """
    source, target = root / ".claude/skills", berth / ".claude/skills"
    if not source.is_dir() or source.resolve() == target.resolve():
        return []
    faults = []
    for skill in sorted(source.iterdir()):
        if not skill.is_dir() or (target / skill.name).exists():
            continue
        try:
            shutil.copytree(skill, target / skill.name, symlinks=True)
        except OSError as fault:
            faults.append(f"the skill {skill.name} could not be carried into {berth} ({fault})")
    return faults


def berth(root: Path, slice_id: str, branch: str, base: str) -> tuple[Path | None, str]:
    """The slice's own worktree, made where it is not there yet. (where, why not).

    None where there is no commit to make one from — a harbour with no history — or git refused; the
    caller decides whether the checkout itself will do, which it will only while nothing else is in it.
    """
    if git(root, "rev-parse", "--verify", "--quiet", "HEAD").returncode != 0:
        return None, "this checkout has no commit yet, so there is nothing to make a worktree from"
    found = checked_out(root, branch) or mid_rebase(root, branch)
    if found is None:
        found = root.parent / f"{root.name}-{slice_id}"
        if found.exists():
            # Both steps, because nothing re-checks the berth and a slice with an open park is skipped:
            # hr-test-2's L04 was told go without the berth being moved, and parked again.
            return None, (f"{found} is already there and is not a worktree on {branch}. Move it, or "
                          f"check {branch} out in it, then answer this park (say go) and the slice is "
                          f"carried on")
        made = add_worktree(root, found, branch, base)
        if made.returncode != 0:
            said = (made.stderr or made.stdout).strip().splitlines()
            return None, f"a worktree for {branch} could not be made: {said[-1] if said else 'git failed'}"
    notes = [note for note in (linked(root, found), furnished(root, found)) if note]
    return found, "; ".join(notes)


def add_worktree(root: Path, found: Path, branch: str, base: str) -> subprocess.CompletedProcess[str]:
    """`git worktree add`, tried again where a sibling's was half-made at the same instant.

    Captains abreast make their berths together, and git reads every other worktree's admin folder while it
    makes one: on Windows a sibling's `.git/worktrees/<name>/commondir` can be there and still empty, and
    git refuses with `failed to read ... commondir`. The berth was then parked as unmakeable for a race that
    was over a moment later. Whether the branch exists is asked each time, because `-b` makes it before the
    worktree and a failed attempt can leave it behind.
    """
    for attempt in range(4):
        exists = git(root, "rev-parse", "--verify", "--quiet", f"refs/heads/{branch}").returncode == 0
        # `--no-track`: cut from `origin/main`, git otherwise writes the branch an upstream in `.git/config`,
        # and captains abreast each writing that file was a berth refused with the branch made and nothing
        # else — manda's S72, S78, S83 and S97 each parked for a person on a command that works when run again.
        made = (git(root, "worktree", "add", "--quiet", str(found), branch) if exists
                else git(root, "worktree", "add", "--quiet", "--no-track", "-b", branch, str(found), base or "HEAD"))
        # Tried again where a sibling's was half-made, and where this attempt made the branch and no berth.
        half = not exists and git(root, "rev-parse", "--verify", "--quiet", f"refs/heads/{branch}").returncode == 0
        if made.returncode == 0 or found.exists() or not ("worktrees/" in (made.stderr or "") or half):
            return made
        time.sleep(0.25 * (attempt + 1))
    return made


def leave(root: Path, berth: Path) -> str:
    """Remove a merged slice's worktree, or say why it was kept. Never the project's own checkout.

    **What runs there is stopped before the folder goes.** manda's S96 merged with its dev server and an index
    daemon still writing into the berth: git deleted the tree while they wrote `.vite/` and `.codegraph/` back
    into it, failed with "Directory not empty" — having already dropped the worktree from its list — and the
    folder sat beside the project from then on, where no tidy looks and where `berth()` refuses the slice id
    if it is ever worked again. So the slice's own processes stop first, and a folder git leaves behind is
    removed outright: nothing in it is work, because `unlanded` has just said the tracked files hold none.
    """
    if berth.resolve() == root.resolve():
        return ""
    for here in places(berth):
        if os.name == "nt" and is_link(here):  # pragma: no cover - the other platform's branch
            # Git reads the junction as a folder of the worktree's own and keeps the berth; `rmdir` takes
            # the junction alone, and the deck logs it joins are not touched.
            os.rmdir(here)
    branch = git(berth, "rev-parse", "--abbrev-ref", "HEAD").stdout.strip()
    # Git keeps a worktree that holds anything it does not track, and a merged slice's berth always does: a
    # build's output, a screenshot, a log. Those were never the slice's work, so they go with it. What stays
    # is a berth whose *tracked* files were edited and not committed, which is work nobody has landed.
    edited = unlanded(berth)
    if edited:
        return (f"{berth} was kept: {len(edited)} tracked file(s) there are edited and not committed "
                f"({', '.join(edited[:3])}{', …' if len(edited) > 3 else ''}); commit or discard them, then "
                f"`python3 scripts/agents/fleet.py tidy`")
    ended = stop_processes(berth)
    gone = git(root, "worktree", "remove", "--force", str(berth))
    if gone.returncode != 0 and registered(root, berth):
        said = (gone.stderr or gone.stdout).strip().splitlines()
        return f"{berth} was kept: {said[-1] if said else 'git would not remove it'}"
    left = cleared(berth)
    if left:
        return f"{berth} was kept: git let it go and {left}"
    stopped = stop_services(berth)
    if branch and branch != "HEAD" and git(root, "branch", "--remotes", "--contains", branch).stdout.strip():
        git(root, "branch", "--delete", "--force", branch)  # the forge holds every commit of it
    said = [f"{ended} process(es) still running in {berth.name} were stopped" if ended else "",
            f"{stopped} container(s) of {berth.name} were still up and were removed" if stopped else ""]
    return "; ".join(one for one in said if one)


def registered(root: Path, where: Path) -> bool:
    """Whether git still lists `where` as one of this repository's worktrees."""
    return any(path == where.resolve() for path, _, _ in worktrees(root))


def worktrees(root: Path) -> list[tuple[Path, str, str]]:
    """Every worktree git lists for this repository: (where, its HEAD commit, its branch or "")."""
    found: list[tuple[Path, str, str]] = []
    for block in git(root, "worktree", "list", "--porcelain").stdout.split("\n\n"):
        fields = dict(line.partition(" ")[::2] for line in block.splitlines() if line.strip())
        if fields.get("worktree"):
            branch = fields.get("branch", "").removeprefix("refs/heads/")
            found.append((Path(fields["worktree"]).resolve(), fields.get("HEAD", ""), branch))
    return found


def cleared(folder: Path) -> str:
    """Remove what is left of a folder, links inside it taken as links and never followed. Why it could not
    be, or nothing.

    Tried a few times, because something stopped a moment ago may still be closing a file, and on Windows a
    read-only file is made writable first rather than refused.
    """
    if not folder.exists() and not folder.is_symlink():
        return ""
    for here in places(folder):
        if is_link(here):  # the project's deck logs: the link goes, what it reaches is never touched
            try:
                here.rmdir() if os.name == "nt" else here.unlink()
            except OSError:
                pass

    def writable(function: Any, path: str, _: Any) -> None:
        os.chmod(path, stat.S_IWRITE)
        function(path)

    fault: OSError | None = None
    for attempt in range(3):
        try:
            if sys.version_info >= (3, 12):
                shutil.rmtree(folder, onexc=writable)
            else:  # pragma: no cover - the older interpreter's spelling
                shutil.rmtree(folder, onerror=writable)
            return ""
        except FileNotFoundError:
            return ""
        except OSError as caught:
            fault = caught
            time.sleep(0.5 * (attempt + 1))
    return f"its folder could not be removed ({fault})"


#: How long a process is given to end after it is asked, before it is made to.
GRACE = 5


def stop_processes(folder: Path) -> int:
    """End what a merged slice left running in its folder, best effort. How many processes were asked to stop.

    Two kinds are the slice's. **The Try it processes its story ran**: `try_it.py` starts each with a session
    of its own and records its pid in the berth's own Try it state, so the whole group goes — the dev server's
    children with it. **Any process whose working directory is inside the folder**, such as an index daemon
    watching it or a dev server a session started by hand. Never this process or one it was started by, and
    never a process somewhere else: a pid recorded long ago that now leads no group of its own is somebody
    else's, and is left. Where the platform cannot say a process's directory — Windows — only the recorded
    pids are ended.
    """
    spared = ancestry()
    recorded = [pid for pid in try_it_pids(folder) if pid not in spared and leads_group(pid)]
    found = [pid for pid in working_in(folder) if pid not in spared and pid not in recorded]
    for pid in recorded:
        end(pid, group=True, hard=False)
    for pid in found:
        end(pid, group=False, hard=False)
    deadline = time.monotonic() + GRACE
    while any(alive(pid) for pid in recorded + found) and time.monotonic() < deadline:
        time.sleep(0.2)
    for pid in recorded:
        if alive(pid):
            end(pid, group=True, hard=True)
    for pid in found:
        if alive(pid):
            end(pid, group=False, hard=True)
    return len(recorded) + len(found)


def try_it_pids(folder: Path) -> list[int]:
    """Every pid the folder's own Try it state records: each app's and what runs beside it, and the run that
    started them. Where the state lives now and where it lived before the run state moved."""
    found: list[int] = []
    for home in {logs.run_dir(folder) / "try-it", folder / logs.RUN / "try-it"}:
        state = talk.read_json(home / "state.json")
        if not isinstance(state, dict):
            continue
        pids = state.get("pids") if isinstance(state.get("pids"), dict) else {}
        for value in [*pids.values(), state.get("runner")]:
            try:
                pid = int(value)
            except (TypeError, ValueError):
                continue
            if pid > 0 and pid not in found:
                found.append(pid)
    return found


def leads_group(pid: int) -> bool:
    """Whether the pid is alive and leads a process group, as every process Try it starts does. On Windows,
    which has no groups, whether it is alive."""
    if not alive(pid):
        return False
    if os.name == "nt":  # pragma: no cover - the other platform's branch
        return True
    try:
        return os.getpgid(pid) == pid
    except OSError:
        return False


def working_in(folder: Path) -> list[int]:
    """The processes whose working directory is the folder or inside it, where the platform can say.

    `/proc` where there is one; `lsof` where there is not (macOS); nothing on Windows, which keeps another
    process's directory where only a debugger reads it.
    """
    inside = folder.resolve()
    found: list[int] = []
    proc = Path("/proc")
    if os.name != "nt" and (proc / "self/cwd").exists():
        for entry in proc.iterdir():
            if not entry.name.isdigit():
                continue
            try:
                cwd = Path(os.readlink(entry / "cwd"))
            except OSError:
                continue
            if cwd.is_relative_to(inside):
                found.append(int(entry.name))
        return found
    if os.name == "nt" or shutil.which("lsof") is None:
        return found
    try:
        listed = subprocess.run(["lsof", "-nP", "-w", "-d", "cwd", "-Fpn"], capture_output=True, text=True,
                                check=False, timeout=DOCKER_WAIT, encoding="utf-8", errors="replace")
    except (OSError, subprocess.SubprocessError):
        return found
    pid = 0
    for line in listed.stdout.splitlines():
        if line.startswith("p") and line[1:].isdigit():
            pid = int(line[1:])
        elif line.startswith("n") and pid and Path(line[1:]).is_relative_to(inside) and pid not in found:
            found.append(pid)
    return found


def ancestry() -> set[int]:
    """This process and every process above it, which a tidy run from inside a berth must not end."""
    found = {os.getpid()}
    pid = os.getppid()
    while pid > 1 and pid not in found and len(found) < 64:
        found.add(pid)
        if os.name == "nt":  # pragma: no cover - the other platform's branch
            break
        try:
            asked = subprocess.run(["ps", "-o", "ppid=", "-p", str(pid)], capture_output=True, text=True,
                                   check=False, timeout=5)
            pid = int(asked.stdout.strip() or 0)
        except (OSError, subprocess.SubprocessError, ValueError):
            break
    return found


def alive(pid: int) -> bool:
    """Whether that process is still running, asked without touching it. Windows is asked through the process
    handle, because signal 0 there is `CTRL_C_EVENT` to the whole console, as `try_it.py` says."""
    if pid <= 0:
        return False
    if os.name == "nt":  # pragma: no cover - the other platform's branch
        import ctypes  # noqa: PLC0415 — Windows only

        kernel = ctypes.windll.kernel32  # type: ignore[attr-defined]
        handle = kernel.OpenProcess(0x1000, False, pid)
        if not handle:
            return False
        try:
            code = ctypes.c_ulong()
            return bool(kernel.GetExitCodeProcess(handle, ctypes.byref(code))) and code.value == 259
        finally:
            kernel.CloseHandle(handle)
    try:
        os.kill(pid, 0)
    except (OSError, ValueError):
        return False
    try:  # a child of this process that has ended is a zombie until it is reaped, and not running
        done, _ = os.waitpid(pid, os.WNOHANG)
        return done == 0
    except ChildProcessError:
        return True
    except OSError:
        return True


def end(pid: int, group: bool, hard: bool) -> None:
    """Ask a process — its whole group, where `group` — to end, or make it. Windows ends the tree through
    `taskkill /T`, as `try_it.py` does."""
    try:
        if os.name == "nt":  # pragma: no cover - the other platform's branch
            subprocess.run(["taskkill", "/T", *(["/F"] if hard else []), "/PID", str(pid)], capture_output=True,
                           check=False, timeout=DOCKER_WAIT)
        elif group:
            os.killpg(pid, signal.SIGKILL if hard else signal.SIGTERM)
        else:
            os.kill(pid, signal.SIGKILL if hard else signal.SIGTERM)
    except (OSError, subprocess.SubprocessError):
        pass


def unlanded(berth: Path) -> list[str]:
    """The tracked files of this worktree that are edited or staged and not committed. Untracked files are
    not work: they are what a build, a demo or a session left lying."""
    said = git(berth, "status", "--porcelain", "--untracked-files=no").stdout.splitlines()
    return [line[3:].strip() for line in said if line.strip()]


def berths_of(root: Path) -> list[tuple[str, Path]]:
    """Every slice worktree this project has beside it: (slice id, where), read from git's own list, so a
    folder that merely has the name is never taken for one."""
    found: list[tuple[str, Path]] = []
    where = ""
    for line in git(root, "worktree", "list", "--porcelain").stdout.splitlines():
        if line.startswith("worktree "):
            where = line.partition(" ")[2]
        elif line.startswith("branch refs/heads/slice/") and where:
            path = Path(where)
            if path.resolve() != root.resolve() and path.is_dir():
                found.append((line.rpartition("/")[2], path))
    return found


def tidy(root: Path, merged: set[str], flying: set[str], say: bool = True) -> list[str]:
    """Clear away the berths of slices that have merged, and git's record of berths that are gone. One line
    per berth about what was done with it or why it stays.

    A berth was only ever removed in the moment its slice merged, by the captain that merged it: one that
    was kept then, or whose captain was stopped first, stayed beside the project for good, and a machine
    that had run three projects held thirty folders nobody would come back for. A berth whose slice has not
    merged is never removed here: it is listed, with what it holds, for a person to decide.

    Two more kinds go. **The folder of a merged slice that is no longer a worktree** (`stranded`), which a
    removal raced by a running process leaves behind. **A delegate's worktree under `.claude/worktrees/`**
    whose commit trunk already holds (`delegates`), which the harness makes for a delegated agent and
    cleans only while it is unchanged: manda held 52 of them, 36 GB.
    """
    lines: list[str] = []
    git(root, "worktree", "prune")
    for slice_id, where in berths_of(root):
        if slice_id in flying:
            continue
        if slice_id in merged:
            kept = leave(root, where)
            lines.append(kept if kept and "was kept" in kept else f"{where.name}: {slice_id} is merged; removed")
        elif say:
            edited = len(unlanded(where))
            lines.append(f"{where.name}: {slice_id} has not merged, so it stays"
                         + (f" ({edited} tracked file(s) edited and not committed)" if edited else "")
                         + f"; `git worktree remove --force {where}` removes it and keeps its branch")
    lines += stranded(root, merged - flying)
    lines += delegates(root, say)
    git(root, "worktree", "prune")
    return lines


def stranded(root: Path, merged: set[str]) -> list[str]:
    """Remove the folder of each merged slice that is still beside the project and no longer a worktree.

    `berths_of` reads git's list, so a folder git forgot halfway through removing it was never seen again,
    and `berth()` then refused the slice id for good. The name is the chart's, `<project>-<slice id>`, and the
    slice has merged; a folder of that name that is a repository or a worktree of anything — it holds a
    `.git` — is somebody's and is left, and so is one of a slice that has not merged.
    """
    lines: list[str] = []
    listed = {path for path, _, _ in worktrees(root)}
    for slice_id in sorted(merged):
        folder = root.parent / f"{root.name}-{slice_id}"
        if not folder.is_dir() or folder.is_symlink() or folder.resolve() in listed:
            continue
        if (folder / ".git").exists() or (folder / ".git").is_symlink():
            continue
        ended = stop_processes(folder)
        left = cleared(folder)
        if left:
            lines.append(f"{folder} was kept: {slice_id} is merged and no longer a worktree, and {left}")
            continue
        stopped = stop_services(folder)
        extra = [f"{ended} process(es) stopped" if ended else "", f"{stopped} container(s) removed" if stopped else ""]
        said = "; ".join(one for one in extra if one)
        lines.append(f"{folder.name}: {slice_id} is merged and its folder was no longer a worktree; removed"
                     + (f" ({said})" if said else ""))
    return lines


def trunk_refs(root: Path) -> list[str]:
    """The refs that say what trunk holds, local and remote, where they exist."""
    return [ref for ref in ("main", "master", "origin/main", "origin/master")
            if git(root, "rev-parse", "--verify", "--quiet", ref).returncode == 0]


def is_delegate(where: Path) -> bool:
    """Whether a worktree is one the harness made for a delegated agent: under a `.claude/worktrees/`."""
    parts = where.parts
    return any(parts[at:at + 2] == (".claude", "worktrees") for at in range(len(parts) - 2))


def delegates(root: Path, say: bool = True) -> list[str]:
    """Remove each delegate's worktree whose commit trunk holds, with its branch; leave every other one.

    Only worktrees git lists, so a folder there that is not one is never touched; never one whose tracked files
    are edited and not committed; never one whose commit trunk does not hold, which is work that has not
    landed — said once, as a count, where `say`.
    """
    refs = trunk_refs(root)
    if not refs:
        return []
    lines: list[str] = []
    held = 0
    for where, head, branch in worktrees(root):
        if where == root.resolve() or not is_delegate(where):
            continue
        landed = bool(head) and any(git(root, "merge-base", "--is-ancestor", head, ref).returncode == 0
                                    for ref in refs)
        if not landed or not where.is_dir() or unlanded(where):
            held += 1
            continue
        ended = stop_processes(where)
        gone = git(root, "worktree", "remove", "--force", str(where))
        if gone.returncode != 0 and registered(root, where):
            said = (gone.stderr or gone.stdout).strip().splitlines()
            lines.append(f"{where} was kept: {said[-1] if said else 'git would not remove it'}")
            continue
        left = cleared(where)
        if branch:
            git(root, "branch", "--delete", "--force", branch)  # every commit of it is on trunk
        lines.append(f"{where.name}: a delegate's worktree whose work trunk holds; removed"
                     + (f" ({ended} process(es) stopped)" if ended else "") + (f", though {left}" if left else ""))
    if held and say:
        lines.append(f"{held} delegate worktree(s) under .claude/worktrees/ hold work trunk does not, or edits "
                     f"nobody committed, so they stay; `git worktree list` names them")
    return lines


#: How long docker is given to answer. A daemon that is not running answers at once; one that hangs is not
#: allowed to hold a captain that has just merged.
DOCKER_WAIT = 20


def stop_services(berth: Path) -> int:
    """Remove the containers a merged slice's berth left running, with their volumes. How many there were.

    lean-coffee-club's MT1 merged and its worktree was removed, and two hours later its database, its second
    database and its sign-in server were still up, holding their ports and their memory: nothing owned them
    once the session that started them had ended. Two kinds are the berth's: a compose project started in it,
    which docker labels with the directory, and a container named after it — `<berth's folder>-…`, lower
    case, which is how a session names one it starts by hand. The trailing hyphen is what keeps `…-mt1-`
    from taking `…-mt10-`. Where docker is not installed or does not answer there is nothing to do, and a
    container that will not go is left: the merge has happened, and this is housekeeping.
    """
    if shutil.which("docker") is None:
        return 0
    found: set[str] = set()
    for chosen in (f"label=com.docker.compose.project.working_dir={berth}", f"name=^/?{berth.name.lower()}-"):
        try:
            listed = subprocess.run(["docker", "ps", "--all", "--quiet", "--filter", chosen], capture_output=True,
                                    text=True, check=False, timeout=DOCKER_WAIT)
        except (OSError, subprocess.SubprocessError):
            return 0
        found.update(listed.stdout.split() if listed.returncode == 0 else [])
    if not found:
        return 0
    try:
        removed = subprocess.run(["docker", "rm", "--force", "--volumes", *sorted(found)], capture_output=True,
                                 text=True, check=False, timeout=DOCKER_WAIT * 3)
    except (OSError, subprocess.SubprocessError):
        return 0
    return len(removed.stdout.split())
