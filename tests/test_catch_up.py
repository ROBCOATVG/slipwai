"""The catch-up notes a migration leaves behind, and the one thing they have to stay: readable.

The module had no suite until a real migration was run against a real version 1 project — `warbook`,
generated by 1.6.2, migrated to 2.0.0.dev0 — and the page it wrote had a fifteen-hundred-word paragraph in
it. Forty-two fragments, each written by whoever made that one change, with their claims concatenated into
one sentence and their catch-up paragraphs into another, so that *"...so `./init` offers them. nothing for
a consumer. A publisher: `slipwai package new` writes the whole repository. nothing. The first install
from a named publisher asks you once."* ran together with nothing saying which change any of it belonged
to.

Nothing was wrong with what it said. `in_flight` is right that a project owes all of a release and not the
first of it, and nothing here summarises or infers — that rule is the module's and it still holds. What
was wrong was that the two halves of each fragment were read apart and joined separately, so the thing a
reader needs to act — *this change asks this of you* — was the one thing the page had thrown away.

So the tests that matter here are about pairing and about shape: every fragment gets its own line, each
line names its own change, and a fragment that wrote no catch-up paragraph is said to have written none
rather than being dropped or read as asking nothing.
"""
from __future__ import annotations

import os
import subprocess
import sys
import tempfile
import unittest
from datetime import UTC, datetime
from pathlib import Path

import checkout_packages  # noqa: F401

from slipwai import catch_up
from slipwai.assets import NOTES
from slipwai.catch_up_page import ARCHIVE, SET_UP, archive

FRAGMENT = """{level}

**{claim}** What it changed, at whatever length the author wanted, wrapped across
lines the way the changelog wraps its prose.
{note}"""
NOTE = "\n**Catch-up:** {owed}\n"
# Run by `EncodingTest` in a process whose locale encoding is ASCII. Prints only ASCII, because a probe
# that cannot write its own answer under `LC_ALL=C` would fail for a reason that is not the one under test.
PROBE = """
import sys
from pathlib import Path

from slipwai import catch_up

found = catch_up.released(Path(sys.argv[1]))
sys.stdout.write(" ".join(part or "?" for part in found[0][:2]) if found else "no entries")
"""


def written(root: Path, name: str, claim: str, owed: str | None, level: str = "MINOR") -> None:
    directory = root / "changelog.d"
    directory.mkdir(parents=True, exist_ok=True)
    (directory / f"{name}.md").write_text(
        FRAGMENT.format(level=level, claim=claim, note="" if owed is None else NOTE.format(owed=owed)),
        encoding="utf-8",
    )


class InFlightTest(unittest.TestCase):
    """A release still being written: its entry is its fragments, a line each."""

    def setUp(self) -> None:
        self.root = Path(tempfile.mkdtemp())
        (self.root / "CHANGELOG.md").write_text("# Changelog\n", encoding="utf-8")

    def entry(self) -> catch_up.Entry:
        found = catch_up.in_flight(self.root, "3.1.0.dev2")
        self.assertEqual(len(found), 1, "the release in flight has no entry")
        return found[0]

    def test_the_entry_is_the_release_the_snapshot_is_heading_for(self) -> None:
        written(self.root, "a-first", "The first thing.", "`slipwai migrate`.", level="MAJOR")
        number, level, _claim, _owed = self.entry()
        self.assertEqual((number, level), ("3.1.0", "MAJOR"))

    def test_every_fragment_owes_on_a_line_of_its_own_naming_its_own_change(self) -> None:
        """The whole of the defect: which change is asking is the one thing a reader needs."""
        written(self.root, "a-first", "The first thing.", "Run `slipwai migrate`.")
        written(self.root, "b-second", "The second thing.", "nothing for a consumer.")
        _number, _level, claim, owed = self.entry()
        self.assertEqual(owed, "- **The first thing.** Run `slipwai migrate`.\n"
                               "- **The second thing.** nothing for a consumer.")
        self.assertEqual(claim, "- The first thing.\n- The second thing.")

    def test_a_fragment_with_no_catch_up_paragraph_is_said_to_have_written_none(self) -> None:
        """Not dropped, and not read as asking nothing: that would be a promise this cannot make."""
        written(self.root, "a-first", "The first thing.", None)
        _number, _level, _claim, owed = self.entry()
        assert owed is not None
        self.assertIn("The first thing.", owed)
        self.assertIn("no catch-up paragraph", owed)

    def test_a_fragment_with_no_claim_is_still_a_line(self) -> None:
        (self.root / "changelog.d").mkdir(parents=True, exist_ok=True)
        (self.root / "changelog.d/a-bare.md").write_text(
            "MINOR\n\nNo claim in bold anywhere.\n\n**Catch-up:** Run it twice.\n", encoding="utf-8")
        _number, _level, claim, owed = self.entry()
        assert owed is not None
        self.assertIn("Run it twice.", owed)
        self.assertIn(catch_up.NO_CLAIM, owed)
        self.assertEqual(claim, "(the fragments for this version state no headline)")

    def test_no_fragments_is_no_entry_rather_than_an_empty_one(self) -> None:
        self.assertEqual(catch_up.in_flight(self.root, "3.1.0.dev2"), [])

    def test_a_release_already_in_the_changelog_is_not_also_in_flight(self) -> None:
        """Otherwise a project would be told twice, once from the fragments and once from the entry."""
        written(self.root, "a-first", "The first thing.", "Run it.")
        (self.root / "CHANGELOG.md").write_text(
            "# Changelog\n\n## 3.1.0 — MINOR\n\n**The first thing.**\n\n**Catch-up:** Run it.\n",
            encoding="utf-8")
        self.assertEqual(catch_up.in_flight(self.root, "3.1.0.dev2"), [])


class ListingTest(unittest.TestCase):
    """How an entry is printed, which differs by how many lines it has rather than by where it came from."""

    def test_a_released_entrys_one_paragraph_stays_on_the_line_that_introduces_it(self) -> None:
        said = catch_up.listing([("1.2.0", "MINOR", "It changed.", "Run `slipwai migrate`.")])
        self.assertIn("**Owes:** Run `slipwai migrate`.", said)

    def test_a_list_starts_below_the_words_that_introduce_it(self) -> None:
        """`**Owes:** - a` is not a list in any Markdown renderer, and this page is read rendered."""
        said = catch_up.listing([("2.0.0", "MAJOR", "- a\n- b", "- **a** Run it.\n- **b** nothing.")])
        self.assertIn("**Owes:**", said)
        self.assertNotIn("**Owes:** - **a** Run it.", "\n".join(said))
        self.assertEqual(said[said.index("**Owes:**") + 1], "")

    def test_an_entry_whose_author_wrote_nothing_says_that_and_not_nothing(self) -> None:
        said = catch_up.listing([("1.2.0", None, "It changed.", None)])
        self.assertIn("**Owes:** nothing recorded for a repository that already existed.", said)


class ShippedTest(unittest.TestCase):
    """The keel's own fragments, which is the release this was found on."""

    def test_the_release_in_flight_renders_one_line_per_fragment(self) -> None:
        found = catch_up.in_flight()
        if not found:  # pragma: no cover - between a release being cut and the next fragment
            self.skipTest("no release is in flight in this checkout")
        _number, _level, claim, owed = found[0]
        assert owed is not None
        from slipwai import changelog  # noqa: PLC0415
        self.assertEqual(len(owed.splitlines()), len(changelog.fragments(tolerant=True)))
        self.assertEqual(len(claim.splitlines()), len(changelog.fragments(tolerant=True)))
        for line in owed.splitlines():
            with self.subTest(line=line[:60]):
                self.assertTrue(line.startswith("- **"), "a line does not name the change it belongs to")


class EncodingTest(unittest.TestCase):
    """`released` reads a file this repository writes as UTF-8 on a machine whose locale is not.

    `read_text()` with no encoding is UTF-8 on macOS and Linux and cp1252 on Windows, so the defect was
    invisible on every laptop and red on one CI runner. Forcing the locale in a subprocess is what
    reproduces it anywhere, which is the point of having it here rather than trusting the Windows job to
    say so a second time.
    """

    def test_a_changelog_is_read_as_utf8_whatever_the_locale_says(self) -> None:
        """The em-dash in `## 3.1.0 — MINOR` is what `ENTRY` matches on, so a wrong decoding reads no
        entries at all — and `in_flight` then offers a project the release it already has."""
        root = Path(tempfile.mkdtemp())
        (root / "CHANGELOG.md").write_text(
            "# Changelog\n\n## 3.1.0 — MINOR\n\n**The first thing.**\n", encoding="utf-8")
        self.assertEqual(self.under_a_non_utf8_locale(root / "CHANGELOG.md"), "3.1.0 MINOR")

    def under_a_non_utf8_locale(self, changelog_file: Path) -> str:
        """What `released` makes of the file in a process whose locale encoding is ASCII.

        `PYTHONIOENCODING` is named so the probe can print what it found; it does not touch
        `locale.getencoding()`, which is what `read_text()` falls back to and what this is testing.
        """
        environment = {
            **os.environ,
            "LC_ALL": "C", "LANG": "C",
            "PYTHONUTF8": "0", "PYTHONCOERCECLOCALE": "0", "PYTHONIOENCODING": "utf-8",
            "PYTHONPATH": str(Path(catch_up.__file__).resolve().parents[1]),
        }
        result = subprocess.run([sys.executable, "-c", PROBE, str(changelog_file)],
                                text=True, capture_output=True, env=environment)
        self.assertEqual(result.returncode, 0, result.stderr)
        return result.stdout.strip()


class SetUpTest(unittest.TestCase):
    """Every page opens with the way from a merge to a project its coding agent can work in.

    A migration that stopped at conflicts once left the rest of that way — `migrate` again, `make agents`, a
    new session — to a report that scrolled away, and a project could be merged with its agent still reading
    the old ladder. So the page carries it, whether or not this run conflicted.
    """

    STEPS = ("git diff --name-only --diff-filter=U", "git commit", "`slipwai migrate` again", "`make agents`",
             "`make check-agents`", "new session", "make verify")

    def page(self, conflicts: tuple[str, ...] = ()) -> str:
        return catch_up.notes("demo", "1.6.0", "2.0.0", conflicts=conflicts)

    def test_every_page_carries_the_whole_path_in_order_conflicts_or_not(self) -> None:
        for page in (self.page(), self.page(("commands/sail.md",))):
            section = page.split(f"## {SET_UP}", 1)[1]
            places = [section.index(step) for step in self.STEPS]
            self.assertEqual(places, sorted(places), "the steps are out of order")

    def test_it_is_the_first_section_before_anything_owed(self) -> None:
        self.assertEqual(self.page().split("\n## ", 2)[1].splitlines()[0], SET_UP)

    def test_a_conflicted_page_names_each_file_and_starts_at_the_first_step(self) -> None:
        page = self.page(("commands/sail.md", "project.json"))
        self.assertIn("stopped at 2 conflict(s)", page)
        self.assertIn("- `commands/sail.md`", page)
        self.assertIn("- `project.json`", page)
        self.assertIn("Start at step 1.", page)

    def test_a_clean_page_says_where_a_clean_run_starts(self) -> None:
        page = self.page()
        self.assertIn("did steps 1 to 4 itself", page)
        self.assertNotIn("Start at step 1.", page)

    def test_a_generated_command_page_is_taken_from_the_factory_and_re_edited(self) -> None:
        """`--ours` on `commands/sail.md` keeps the old ladder: the page says which side, and why."""
        self.assertIn("take `--theirs` and re-apply your own change", self.page(("commands/sail.md",)))


class StopReportTest(unittest.TestCase):
    """What `migrate` prints when it stops at conflicts: the way on is on the page, and said so."""

    def stopped(self, unwritten: str | None = None) -> str:
        from slipwai.migrate import report
        from slipwai.migration_result import Migration
        from slipwai.replay import Replay

        offered = Replay(Path("demo"), Path("offered"), "demo", 1, "1.6.0", "abc")
        return report(Migration(offered, "1.6.0", ("commands/sail.md",), "1 file changed", unwritten=unwritten))

    def test_it_points_at_the_notes_section_that_sets_the_project_up(self) -> None:
        said = self.stopped()
        self.assertIn(f"`{SET_UP}`", said)
        self.assertIn("make check-agents", said)

    def test_with_no_notes_it_says_the_whole_way_itself(self) -> None:
        """No page to point at, so the steps after the resolving commit are printed rather than lost."""
        said = self.stopped(unwritten="disk full")
        self.assertNotIn(f"`{SET_UP}`", said)
        for step in ("`slipwai migrate` again", "`make agents`", "`make check-agents`", "new agent session"):
            self.assertIn(step, said)


class ArchiveTest(unittest.TestCase):
    """A catch-up page is never deleted or overwritten: it is moved under the archive, once, and kept.

    `warbook` has a page from its upgrade to 2.0.0.dev2, written before pages named their own archive path,
    and the next migration must not lose it.
    """

    OLD = "# Catch up: warbook, 2.0.0.dev0 to 2.0.0.dev2\n\nWhat that upgrade asked.\n"

    def setUp(self) -> None:
        self.root = Path(tempfile.mkdtemp())
        (self.root / NOTES).parent.mkdir(parents=True)

    def page(self, text: str, mtime: float = 1_760_000_000) -> Path:
        path = self.root / NOTES
        path.write_text(text, encoding="utf-8")
        os.utime(path, (mtime, mtime))
        return path

    def moved(self) -> Path:
        """Where `archive` moved the page, which this suite has always just written."""
        target = archive(self.root)
        assert target is not None, "there was a page to archive"
        return target

    def archived(self) -> list[Path]:
        return sorted((self.root / ARCHIVE).glob("*.md"))

    def test_an_old_page_is_named_from_the_versions_it_recorded_and_when_it_was_written(self) -> None:
        self.page(self.OLD)
        moved = self.moved()
        self.assertEqual(moved, self.root / ARCHIVE / "2.0.0.dev0-to-2.0.0.dev2-20251009T085320Z.md")
        self.assertEqual(moved.read_text(encoding="utf-8"), self.OLD)
        self.assertFalse((self.root / NOTES).exists())

    def test_a_page_that_recorded_no_version_is_named_from_its_time_alone(self) -> None:
        self.page("A page with no title.\n")
        self.assertEqual(self.moved().name, "unrecorded-to-unrecorded-20251009T085320Z.md")

    def test_a_page_that_names_its_archive_path_goes_there(self) -> None:
        self.page(catch_up.notes("demo", "1.6.0", "2.0.0", when=datetime(2026, 10, 17, 9, 30, tzinfo=UTC)))
        self.assertEqual(self.moved().name, "1.6.0-to-2.0.0-20261017T093000Z.md")

    def test_it_never_overwrites_a_different_page_already_archived_under_that_name(self) -> None:
        self.page(self.OLD)
        first = self.moved()
        self.page(self.OLD.replace("asked", "asked, edited"))
        second = self.moved()
        self.assertNotEqual(first, second)
        self.assertEqual(second.name, first.name.replace(".md", "-2.md"))
        self.assertEqual(first.read_text(encoding="utf-8"), self.OLD)

    def test_the_same_page_is_never_archived_twice(self) -> None:
        """A copy restored over an archive that already holds it is the duplicate, and goes."""
        self.page(self.OLD)
        archive(self.root)
        self.page(self.OLD)
        archive(self.root)
        self.assertEqual(len(self.archived()), 1)
        self.assertIsNone(archive(self.root), "with no page there is nothing to archive")

    def test_a_migration_archives_the_page_it_finds_and_writes_a_fresh_one(self) -> None:
        """From a project with the old page to one with the page archived and a new one in its place; and a
        second migration archives that one in turn, losing neither."""
        from slipwai.migrate import write_notes

        self.page(self.OLD)
        self.assertIsNone(write_notes(self.root, "warbook", "2.0.0.dev2"))
        fresh = (self.root / NOTES).read_text(encoding="utf-8")
        self.assertIn(f"## {SET_UP}", fresh)
        self.assertEqual([path.read_text(encoding="utf-8") for path in self.archived()], [self.OLD])
        self.assertIsNone(write_notes(self.root, "warbook", "2.0.0.dev2"))
        self.assertEqual(len(self.archived()), 2)
        self.assertIn(fresh, [path.read_text(encoding="utf-8") for path in self.archived()])

    def test_the_archive_is_ignored_like_the_page(self) -> None:
        from slipwai.project.gitignore import RUN_STATE

        self.assertTrue(ARCHIVE.startswith(".slipwai/catch-up/"))
        self.assertIn("catch-up/", RUN_STATE)


